"""Collect and serialize the generated Benchmark results views."""

from collections import defaultdict
import hashlib
import json
from pathlib import Path
import re


DIRECTORY = "benchmark-results"
JSON_FILE = "benchmark-results.json"
GENERATED = "# Generated by scripts/build.py from models/ and benchmarks/. Do not edit.\n"
COST_FIELDS = {"cost", "cost_unit", "cost_source"}


def definition_index(definitions):
    index = defaultdict(list)
    for identifier, definition in definitions:
        versions = (definition.get("version"), *definition.get("compatible_versions", []))
        for version in dict.fromkeys(versions):
            index[definition.get("name"), version, definition.get("metric")].append(identifier)
    return dict(index)


def matching_definitions(result, index):
    key = (result.get("name"), result.get("version", "unspecified"), result.get("metric"))
    return index.get(key, ())


def sort_by_score(rows, higher_is_better):
    direction = -1 if higher_is_better else 1

    def key(row):
        score = row["result"]["score"]
        if isinstance(score, str):
            return (1, 0, row["model_id"])
        return (0, direction * score, row["model_id"])

    return sorted(rows, key=key)


def collect_results(models, definitions):
    index = definition_index(definitions.items())
    matched = {identifier: [] for identifier in sorted(definitions)}
    uncategorized = defaultdict(list)
    unmatched = ambiguous = missing_source = 0
    for model_id, model in sorted(models.items()):
        for result in model.get("benchmarks", []):
            row = {"model_id": model_id, "result": result}
            matches = matching_definitions(result, index)
            missing_source += "source" not in result
            if len(matches) == 1:
                matched[matches[0]].append(row)
            else:
                uncategorized[result["name"]].append(row)
                unmatched += not matches
                ambiguous += bool(matches)

    benchmarks = {identifier: {"results": sort_by_score(rows, definitions[identifier]["higher_is_better"])}
                  for identifier, rows in matched.items()}

    warnings = []
    if unmatched or ambiguous:
        warnings.append(f"Benchmark 定义映射：未匹配 {unmatched} 条，歧义 {ambiguous} 条"
                        "（要求 name/version/metric 匹配或使用定义声明的兼容版本；"
                        "unspecified 定义允许源记录省略版本；原始成绩全部保留）。")
    if missing_source:
        warnings.append(f"{missing_source} 条成绩未提供 source；原始成绩保留，来源需人工核实。")
    return {"benchmarks": benchmarks,
            "uncategorized": {name: {"groups": [], "unranked": rows}
                              for name, rows in sorted(uncategorized.items())}}, warnings


def toml_string(value):
    # JSON basic string escapes also work in TOML. TOML additionally requires escaping DEL.
    return json.dumps(value, ensure_ascii=False).replace("\x7f", r"\u007f")


def toml_key(key):
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else toml_string(key)


def toml_value(value):
    # Source validation and JSON serialization limit these values to JSON-compatible TOML.
    if isinstance(value, str):
        return toml_string(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{toml_key(key)} = {toml_value(item)}"
                               for key, item in sorted(value.items())) + " }"
    return json.dumps(value, allow_nan=False)


def toml_document(document):
    lines = [GENERATED.rstrip("\n")]
    lines.extend(f"{key} = []" for key, entries in document.items() if not entries)
    for table, entries in document.items():
        for row in entries:
            lines.extend(("", f"[[{table}]]", f'model_id = {toml_string(row["model_id"])}',
                          f"[{table}.result]"))
            result = row["result"]
            for key in ["name", "score", *sorted(result.keys() - {"name", "score"})]:
                lines.append(f"{toml_key(key)} = {toml_value(result[key])}")

    return "\n".join(lines) + "\n"


def toml_documents(results):
    documents = {Path(f"{identifier}.toml"): document for identifier, document in results["benchmarks"].items()}
    for name, document in results["uncategorized"].items():
        slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:80].rstrip("-") or "benchmark"
        digest = hashlib.sha256(name.encode("utf-8")).hexdigest()[:16]
        documents[Path("uncategorized") / f"{slug}-{digest}.toml"] = document
    if len({path.as_posix().lower() for path in documents}) != sum(map(len, results.values())):
        raise ValueError(f"{DIRECTORY}/: generated file name collision")
    return {path: toml_document(document) for path, document in documents.items()}


def existing_toml(base):
    directories = (base, base / "uncategorized")
    for directory in directories:
        if directory.is_symlink() or (directory.exists() and not directory.is_dir()):
            raise ValueError(f"{directory}: expected a non-symlink directory")
    contents = {}
    for path in sorted(base.rglob("*.toml")):
        if path.is_symlink() or not path.is_file() or path.parent not in directories:
            raise ValueError(f"{path}: expected a regular TOML file inside a generated results directory")
        contents[path.relative_to(base)] = path.read_text(encoding="utf-8")
    return contents
